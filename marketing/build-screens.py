#!/usr/bin/env python3
"""Bundles marketing/screens/*.jpg into screens.js (data URIs) so index.html works from file://.

Each entry also records the screenshot's size and the colour behind its status bar, which the
page uses to paint a clean status bar over the real one.

Usage: python3 marketing/build-screens.py
"""
import base64, json, os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
screens = {}
for name in sorted(os.listdir(os.path.join(here, 'screens'))):
    if not name.endswith('.jpg'):
        continue
    path = os.path.join(here, 'screens', name)
    im = Image.open(path).convert('RGB')
    with open(path, 'rb') as f:
        data = base64.b64encode(f.read()).decode()
    screens[name[:-4]] = {
        'w': im.width, 'h': im.height,
        'bar': '#%02x%02x%02x' % im.getpixel((12, 12)),
        'src': 'data:image/jpeg;base64,' + data,
    }
with open(os.path.join(here, 'screens.js'), 'w') as f:
    f.write('// Generated by build-screens.py from screens/*.jpg. Do not edit by hand.\n')
    f.write('window.PC_SCREENS = ' + json.dumps(screens) + ';\n')
print(f'{len(screens)} screens -> screens.js ({os.path.getsize(os.path.join(here, "screens.js")) // 1024} KB)')
